    $purchase_name = !empty($_POST['purchase_name']) ? $_POST['purchase_name'] : null;
    $amount = $_POST['amount'];
    $unit_type = $_POST['unit_type'];
    $quantity = $_POST['quantity'];
    $date = $_POST['date'];

    $sql = "INSERT INTO purchases (product_id, purchase_name, amount, unit_type, quantity, date)
            VALUES (?,?,?,?,?,?)";
    $stmt = $conn->prepare($sql);
    
    // Corrected bind_param format string
    $stmt->bind_param("isdsss", $product_id, $purchase_name, $amount, $unit_type, $quantity, $date);
    
   

    if ($stmt->execute()) {
        $message = "✅ Purchase added successfully!";
